"""Render docs/analysis.md from results.json. Every number in the text comes from the results dict."""

from pathlib import Path

FIG = "analysis/figures"


def _pct(x: float, d: int = 0) -> str:
    return f"{100 * x:.{d}f}%"


def _ci(ci, fmt="{:+,.0f}") -> str:
    return f"{fmt.format(ci[0])} to {fmt.format(ci[1])}"


def render(res: dict) -> str:
    m, price, neg, sp, fc, bat = (
        res["meta"],
        res["price_level"],
        res["negative"],
        res["spikes"],
        res["forecast"],
        res["battery"],
    )
    pa, yy = price["aug_oct_2026_vs_2025"], price["year_vs_year"]
    sk = fc["skill"]["models"]
    base = fc["skill"]["baseline"]
    w, cal, wk = sk["lgbm_weather"], sk["lgbm_calendar"], sk["naive_168h"]
    st = bat["strategies"]
    d = bat["differences_per_year"]["lgbm_weather_minus_naive_24h"]
    dcal = bat["differences_per_year"]["lgbm_calendar_minus_naive_24h"]
    iv = fc["interval"]
    p8 = neg["probability_when_residual_low"]["le_8_gw"]
    noise = {n["noise_pct_of_std"]: n for n in fc["noise"] if n.get("noise_pct_of_std") is not None}
    nsum = neg["summary"]
    worst = max(iv["by_regime"], key=lambda r: abs(r["coverage"] - iv["nominal"]))
    best_regime = max(fc["by_regime"], key=lambda r: 1 - r["mae_lgbm_weather"] / r["mae_naive_24h"])
    spike = next(r for r in fc["by_regime"] if r["regime"].startswith("spike"))
    mp = price["monthly_premium"]
    n_months = len(fc["monthly"])
    n_better = sum(1 for r in fc["monthly"] if r["diff"] < 0)
    n_sig = sum(1 for r in fc["monthly"] if r["diff_ci"][1] < 0)

    return f"""# Does a public-data price forecast matter economically? A full analysis

> Generated by `gridpulse analyze` from `{m["market_hours"]:,}` hourly day-ahead prices
> ({m["market_from"][:10]} to {m["market_to"][:10]}) and `{m["walk_forward_hours"]:,}` out-of-sample
> forecast hours. Do not edit by hand: change the code and regenerate.
> Intervals are 95% day-block bootstrap intervals unless stated otherwise.
> An interactive version is in [`analysis/dashboard.html`](analysis/dashboard.html).

## The question

**{res["question"]}**

It is a decision question rather than a modelling one. A forecast is only worth building if acting
on it earns more than the free alternative, and the answer can differ by market condition.
Four sub-questions follow from it, each answered below with one method:

1. What kind of market is this, and has it changed? (price level at equal conditions)
2. When do prices go negative or spike, and are those events forecastable?
3. Is the model statistically better than the naive forecast, and where?
4. Does that improvement turn into money for a battery operator?

## Short answer

| | Result | Evidence |
|---|---|---|
| Statistically better? | **Yes.** Mean absolute error {w["mae"]:.1f} vs {base["mae"]:.1f} EUR/MWh, {_pct(w["skill_vs_baseline"])} lower | 95% interval {_pct(w["skill_ci"][0])} to {_pct(w["skill_ci"][1])}; better in {n_better} of {n_months} months |
| Economically better? | **No measurable difference.** Battery revenue {d["mean"]:+,.0f} EUR/MW/year vs the naive forecast | interval {_ci(d["ci"])}, spans zero |
| Why not? | The naive forecast already earns {_pct(st["naive_24h"]["capture_of_perfect"])} of the perfect-foresight ceiling, and the model stays weak in spikes (a likely, untested explanation) | Sections 3 and 4 |
| Is the model well calibrated? | **No.** The nominal 80% interval covers {_pct(iv["coverage"])} | Section 3 |
| Caveat that matters most | The weather model is fed *observed* weather, i.e. a perfect weather forecast. It is an upper bound | Section 3, noise test |

The honest conclusion: the project's headline accuracy gain is real, but on this evidence it is
not a reason to run a forecasting stack for a 1 MW battery. The cheap forecast is already
{_pct(st["naive_24h"]["capture_of_perfect"])} as good as knowing tomorrow's prices exactly.

## 1. The market moved: same conditions, much higher prices

![Market regime]({FIG}/01_market_regime.png)

For August to mid-October, 2026 against 2025, at the **same residual load** (demand minus wind
and solar) and the same hour of day, the price is **{pa["premium_eur_mwh"]:+.0f} EUR/MWh higher**
(interval {pa["premium_ci"][0]:.0f} to {pa["premium_ci"][1]:.0f}). The average price went from
{pa["mean_price_a"]:.0f} to {pa["mean_price_b"]:.0f} EUR/MWh while average residual load fell
from {pa["mean_residual_a"]:.1f} to {pa["mean_residual_b"]:.1f} GW, so load and renewables
do not explain it. Over a full year the gap is smaller ({yy["premium_eur_mwh"]:+.0f}, interval
{yy["premium_ci"][0]:.0f} to {yy["premium_ci"][1]:.0f}) and it widens month by month:
{", ".join(f"{r['month']}: {r['premium']:+.0f}" for r in mp)} EUR/MWh (April to September).

![Same residual load, higher price]({FIG}/02_same_residual_load_higher_price.png)

This pattern points to the fuel and carbon price level, which the platform does not observe.
**This is a statement about what is *not* explained by load and renewables, not a measured cause.**

The slope is {pa["eur_per_gw_residual"]:.1f} EUR/MWh per GW of residual load
(interval {pa["eur_per_gw_ci"][0]:.1f} to {pa["eur_per_gw_ci"][1]:.1f}): each additional GW the
fossil fleet has to cover raises the price by about that much.

## 2. Negative prices and spikes

![Negative prices by month and hour]({FIG}/03_negative_prices_heatmap.png)

{nsum["hours"]:,} hours ({_pct(nsum["share_of_hours"], 1)}) had a negative price.
{_pct(nsum["midday_share_of_negative"])} of them fall between 10:00 and 16:59 Berlin time, and
{_pct(nsum["weekend_share_of_negative"])} on weekends against a weekend share of
{_pct(nsum["weekend_share_of_all"])} of all hours. Average solar output in negative hours is
{nsum["conditions"]["solar_gw"]["negative_hours_mean"]:.0f} GW against
{nsum["conditions"]["solar_gw"]["other_hours_mean"]:.0f} GW otherwise, while wind is almost the same
({nsum["conditions"]["wind_gw"]["negative_hours_mean"]:.0f} vs
{nsum["conditions"]["wind_gw"]["other_hours_mean"]:.0f} GW): a sunny weekend midday is the trigger.

![Negative price probability]({FIG}/04_negative_probability.png)

Negative prices became **less likely at the same surplus**. When residual load was at or below
8 GW (April to September), the share of negative hours fell from
{_pct(p8["a"]["p"])} (interval {_pct(p8["a"]["ci"][0])} to {_pct(p8["a"]["ci"][1])}) in 2025 to
{_pct(p8["b"]["p"])} ({_pct(p8["b"]["ci"][0])} to {_pct(p8["b"]["ci"][1])}) in 2026. Something
absorbs the surplus better (more storage, flexible demand, or curtailment rules); the data cannot
say which.

Price spikes above {sp["threshold"]:.0f} EUR/MWh: {sp["hours"]} hours, {_pct(sp["evening_share"])} of them
in the evening, with average residual load {sp["mean_residual_gw_spike"]:.0f} GW against
{sp["mean_residual_gw_other"]:.0f} GW otherwise and only {sp["mean_wind_gw_spike"]:.1f} GW of wind
against {sp["mean_wind_gw_other"]:.1f} GW: dark, calm evenings.

## 3. Forecast quality

Method: walk-forward evaluation. For each of {n_months} months, the model is trained on
all earlier data only (plus a 60-day validation block), then predicts that month. The target is the
change from the same hour yesterday. Result tables are over {fc["skill"]["n_hours"]:,} hours
({fc["skill"]["n_days"]} days).

![Forecast skill]({FIG}/05_forecast_skill.png)

| Model | MAE (EUR/MWh) | vs same hour yesterday |
|---|---|---|
| Same hour last week | {wk["mae"]:.1f} | {_pct(wk["skill_vs_baseline"])} ({_pct(wk["skill_ci"][0])} to {_pct(wk["skill_ci"][1])}) |
| **Same hour yesterday (baseline)** | **{base["mae"]:.1f}** | |
| Model without weather | {cal["mae"]:.1f} | {_pct(cal["skill_vs_baseline"], 1)} ({_pct(cal["skill_ci"][0], 1)} to {_pct(cal["skill_ci"][1], 1)}) |
| Model with observed weather | **{w["mae"]:.1f}** | **{_pct(w["skill_vs_baseline"])}** ({_pct(w["skill_ci"][0])} to {_pct(w["skill_ci"][1])}) |

Weather is what makes the model work: without it the gain is {_pct(cal["skill_vs_baseline"], 1)} and
the interval includes zero. With it, {n_better} of {n_months} months are better than the baseline
({n_sig} of them with an interval that excludes zero); the remaining months are not distinguishable
or slightly worse, so the gain is not uniform.

**The weather in this model is observed, not forecast.** To see how much that flatters the result,
Gaussian noise (a share of each weather variable's standard deviation) was added to the weather
inputs at prediction time. This is illustrative, not a calibrated forecast-error model:

![Noise sensitivity]({FIG}/06_noise_sensitivity.png)

| Noise | MAE | Gain vs yesterday |
|---|---|---|
{chr(10).join(f"| {k}% of std | {v['mae']:.1f} | {_pct(v['gain'])} ({_pct(v['gain_ci'][0])} to {_pct(v['gain_ci'][1])}) |" for k, v in noise.items())}

At 100% noise the gain shrinks to {_pct(noise[100]["gain"], 1)}, no better than having no weather
at all. The real-world gain therefore lies between those numbers and the headline.

![Error structure]({FIG}/07_error_structure.png)

**Where it wins and loses.** The relative gain is largest in the {best_regime["regime"]} price
regime ({_pct(1 - best_regime["mae_lgbm_weather"] / best_regime["mae_naive_24h"])} lower error). In
spikes above 300 EUR/MWh the model still misses by {spike["mae_lgbm_weather"]:.0f} EUR/MWh on
average ({spike["n"]} hours): it improves on the baseline but remains unreliable exactly where it
would matter.

![Forecast week]({FIG}/08_forecast_week.png)

**Uncertainty is understated.** The model's 10 to 90% interval is meant to cover 80% of hours; it
covers {_pct(iv["coverage"])}. The worst regime is {worst["regime"]} ({_pct(worst["coverage"])},
{worst["n"]} hours). The model is too confident, and more so when it matters.

![Interval coverage]({FIG}/10_interval_coverage.png)

## 4. Does it earn money?

Setup: a 1 MW / 2 MWh battery, round-trip efficiency
{_pct(bat["parameters"]["round_trip_efficiency"])}, {bat["parameters"]["throughput_cost_eur_per_mwh"]:.0f} EUR/MWh
degradation cost, one cycle per day on the day-ahead market, scheduled by exact dynamic programming
from each forecast and paid at the **actual** price. Perfect foresight is the ceiling.

![Battery value]({FIG}/09_battery_value.png)

| Strategy | EUR/MW/year | Share of perfect foresight |
|---|---|---|
{chr(10).join(f"| {k} | {v['eur_per_mw_year']:,.0f} ({v['ci_per_year'][0]:,.0f} to {v['ci_per_year'][1]:,.0f}) | {_pct(v['capture_of_perfect'])} |" for k, v in st.items())}

Over {bat["n_days"]} days the weather model earns {d["mean"]:+,.0f} EUR/MW/year more than yesterday's
price (interval {_ci(d["ci"])}), and the model without weather {dcal["mean"]:+,.0f}
({_ci(dcal["ci"])}). **A {_pct(w["skill_vs_baseline"])} lower forecast error does not move battery
revenue.** The naive forecast already captures {_pct(st["naive_24h"]["capture_of_perfect"])}
of the achievable value because the daily shape (cheap midday, expensive evening) repeats. A likely
second reason (not tested separately): dispatch depends on the *ranking* of hours within a day, and
the error reduction does not necessarily improve that ranking. With noisy weather the model falls clearly *below* the naive
forecast ({st["lgbm_weather_noise50"]["eur_per_mw_year"]:,.0f} EUR/MW/year at 50% noise).

## What this means

* The forecasting work is sound and honestly measured: a {_pct(w["skill_vs_baseline"])} lower error
  than the obvious benchmark, over {n_months} strictly out-of-sample months.
* For a small day-ahead battery operator the same work is not worth much: the benchmark is
  already close to the ceiling. The value would have to come from elsewhere (intraday trading,
  balancing markets, larger spreads, or better spike detection).
* The market itself is the larger story: prices at equal physical conditions are
  {pa["premium_eur_mwh"]:.0f} EUR/MWh higher, negative prices are less likely, and spikes are
  concentrated in dark, low-wind evenings.

## Limitations

* The weather model uses observed weather. Real use needs a numerical weather forecast, which this
  project does not have (see the noise test for the effect).
* One market, roughly two years of prices, one battery configuration. No intraday, balancing or
  ancillary revenue, no network charges, no capacity degradation over time.
* The price premium is a regression residual, not a causal estimate; fuel and carbon prices are not
  in the data.
* Quantile intervals are not conformally calibrated; coverage is reported, not fixed.
* Past results; not trading or investment advice.

## Reproduce

```bash
pip install -e ".[dev,viz]"
gridpulse walk-forward --first-test-month 2025-10-01 --n-months 13   # about 20 min on a laptop
gridpulse analyze                                                      # figures, dashboard, this file
```

Data: SMARD.de (Bundesnetzagentur, CC BY 4.0) and Deutscher Wetterdienst via Bright Sky (CC BY 4.0).
See [data-sources.md](data-sources.md).
"""


def write_report(res: dict, path: str | Path) -> Path:
    out = Path(path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render(res), encoding="utf-8")
    return out
